/**
 * Refresh official Google crawler CIDRs for Edge middleware.
 * Sources: https://developers.google.com/search/docs/crawling-indexing/verifying-googlebot
 *
 * Usage: node scripts/refresh-googlebot-cidrs.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCES = [
  'https://developers.google.com/static/search/apis/ipranges/googlebot.json',
  'https://developers.google.com/static/search/apis/ipranges/special-crawlers.json',
]

const outPath = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/server/googlebot-cidrs.generated.ts')

function collapseIpv6To48(prefixes) {
  const set = new Set()
  for (const cidr of prefixes) {
    const [addr] = cidr.split('/')
    const hextets = addr.split(':').filter(Boolean)
    const head = hextets.slice(0, 3).map((h) => h.toLowerCase())
    while (head.length < 3) head.push('0')
    set.add(`${head.join(':')}::/48`)
  }
  return [...set].sort()
}

function formatTsArray(name, values) {
  const body = values.map((v) => `  ${JSON.stringify(v)},`).join('\n')
  return `export const ${name} = [\n${body}\n] as const\n`
}

const ipv4 = new Set()
const ipv6 = new Set()
const created = []

for (const url of SOURCES) {
  const res = await fetch(url)
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: ${res.status}`)
  }
  const data = await res.json()
  created.push(data.creationTime || 'unknown')
  for (const row of data.prefixes || []) {
    if (row.ipv4Prefix) ipv4.add(row.ipv4Prefix)
    if (row.ipv6Prefix) ipv6.add(row.ipv6Prefix)
  }
}

const v4 = [...ipv4].sort()
const v6 = collapseIpv6To48([...ipv6])

const header = `/**
 * Auto-generated by scripts/refresh-googlebot-cidrs.mjs — do not edit by hand.
 * Official Googlebot + special-crawlers prefixes (not the broad goog.json GCP list).
 * Source dates: ${created.join(', ')}
 */
`

const file = `${header}
${formatTsArray('GOOGLEBOT_IPV4_CIDRS', v4)}
${formatTsArray('GOOGLEBOT_IPV6_CIDRS', v6)}
`

writeFileSync(outPath, file)
console.log(`Wrote ${v4.length} IPv4 + ${v6.length} IPv6 CIDRs to ${outPath}`)
